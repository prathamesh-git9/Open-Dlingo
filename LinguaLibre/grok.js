// LinguaLibre — Grok AI tutor proxy (server-side, keeps your API key secret).
// Uses the xAI API: https://docs.x.ai — set XAI_API_KEY in .env
// 100% unlimited: no rate limits, no energy, no paywall. Bring your own key.

const express = require("express");
const https = require("https");

const XAI_MODEL = process.env.XAI_MODEL || "grok-2-latest";
const router = express.Router();

function callGrok(messages) {
  return new Promise((resolve, reject) => {
    const key = process.env.XAI_API_KEY;
    if (!key) return reject(new Error("NO_API_KEY"));

    const payload = JSON.stringify({
      model: XAI_MODEL,
      messages,
      temperature: 0.4,
      max_tokens: 600
    });

    const req = https.request(
      {
        hostname: "api.x.ai",
        path: "/v1/chat/completions",
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${key}`,
          "Content-Length": Buffer.byteLength(payload)
        }
      },
      (res) => {
        let data = "";
        res.on("data", (c) => (data += c));
        res.on("end", () => {
          try {
            const json = JSON.parse(data);
            if (json.error) return reject(new Error(json.error.message || "Grok error"));
            resolve(json.choices?.[0]?.message?.content || "");
          } catch (e) {
            reject(new Error("Bad response from xAI API"));
          }
        });
      }
    );
    req.on("error", reject);
    req.write(payload);
    req.end();
  });
}

// POST /api/tutor  { message, history, lang } -> AI explanation / chat help
router.post("/tutor", async (req, res) => {
  const { message, history = [], lang = "de" } = req.body || {};
  if (!message) return res.status(400).json({ error: "message required" });
  try {
    const sys = {
      role: "system",
      content: `You are "Lingo", the friendly mascot-tutor of LinguaLibre, a free open-source language-learning app. The user is learning ${lang === "de" ? "German (from English)" : "English (from German)"}. Give short, encouraging, clear answers. Use examples with translations. Keep replies under 150 words.`
    };
    const reply = await callGrok([sys, ...history.slice(-8), { role: "user", content: message }]);
    res.json({ reply });
  } catch (e) {
    res.status(e.message === "NO_API_KEY" ? 501 : 502).json({ error: e.message });
  }
});

// POST /api/explain  { word, lang } -> mini grammar/vocab card generated by Grok
router.post("/explain", async (req, res) => {
  const { word, lang = "de" } = req.body || {};
  if (!word) return res.status(400).json({ error: "word required" });
  try {
    const reply = await callGrok([
      {
        role: "system",
        content: `You generate tiny vocabulary cards for a ${lang === "de" ? "German" : "English"} learner. Reply EXACTLY as JSON: {"translation":"...","example":"...","exampleTranslation":"...","note":"one short grammar tip"}. No markdown.`
      },
      { role: "user", content: `Word/phrase: ${word}` }
    ]);
    const clean = reply.replace(/```json|```/g, "").trim();
    res.json(JSON.parse(clean));
  } catch (e) {
    res.status(e.message === "NO_API_KEY" ? 501 : 502).json({ error: e.message });
  }
});

// POST /api/practice  { lang, topic } -> Grok generates extra practice sentences (unlimited!)
router.post("/practice", async (req, res) => {
  const { lang = "de", topic = "daily life" } = req.body || {};
  try {
    const reply = await callGrok([
      {
        role: "system",
        content: `Create 4 translate exercises for a learner of ${lang === "de" ? "German" : "English"}. Reply EXACTLY as JSON array: [{"source":"...","target":"..."}] where source is in the learner's native language and target in the target language. Simple A1-A2 level, topic: ${topic}. No markdown.`
      }
    ]);
    const clean = reply.replace(/```json|```/g, "").trim();
    res.json({ exercises: JSON.parse(clean) });
  } catch (e) {
    res.status(e.message === "NO_API_KEY" ? 501 : 502).json({ error: e.message });
  }
});

module.exports = router;
